export function getLocalizedSchemeData(scheme: Scheme, lang: string): Scheme {
  const schemeDict = localizedSchemes[scheme.id];
  if (!schemeDict) return scheme;

  const loc = schemeDict[lang] || schemeDict.en;
  if (!loc) return scheme;

  return {
    ...scheme,
    name: loc.name || scheme.name,
    organization: loc.organization || scheme.organization,
    type: loc.type || scheme.type,
    purpose: loc.purpose || scheme.purpose,
    eligibilitySummary: loc.eligibilitySummary || scheme.eligibilitySummary,
    financialAssistance: loc.financialAssistance || scheme.financialAssistance,
    description: loc.description || scheme.description,
    benefits: loc.benefits && loc.benefits.length > 0 ? loc.benefits : scheme.benefits,
  };
}

export function getLocalizedFAQsData(lang: string): LocalizedFAQ[] {
  const list = localizedFAQs[lang] || localizedFAQs.en;
  if (Array.isArray(list)) return list;
  return localizedFAQs.en;
}

export function getLocalizedPartnersData(partnersList: Partner[], lang: string): Partner[] {
  return partnersList.map(p => {
    const pDict = localizedPartners[p.id];
    if (!pDict) return p;
    const loc = pDict[lang] || pDict.en;
    if (!loc) return p;
    return {
      ...p,
      name: loc.name || p.name,
      type: loc.type || p.type,
      address: loc.address || p.address,
      hours: loc.hours || p.hours,
    };
  });
}

